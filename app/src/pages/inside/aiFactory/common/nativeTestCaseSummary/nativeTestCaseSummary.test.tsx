// The repository's Enzyme shim omits its supported attachTo option.
const mountInContainer: (
  element: ReactElement,
  options: { attachTo: HTMLElement },
) => ReturnType<typeof mount> = mount;

const renderSummary = (element: ReactElement) => {
  const container = document.createElement('div');
  return { container, wrapper: mountInContainer(element, { attachTo: container }) };
};

describe('NativeTestCaseSummary', () => {
  test('renders AI identity, Draft status and zero metrics with current-version cost wording', () => {
    const { container, wrapper } = renderSummary(
      <NativeTestCaseSummary
        showIdentity
        summary={{
          isAi: true,
          status: 'DRAFT',
          score: 0,
          isObsolete: true,
          costUsd: 0,
          model: 'auto (default)',
        }}
      />,
    );

    expect(container.textContent).toContain('AI');
    expect(container.textContent).toContain('Draft');
    expect(container.textContent).toContain('★ 0');
    expect(container.textContent).toContain('Model: auto (default)');
    expect(container.textContent).toContain('Current version cost: $0.00');
    expect(wrapper.find('[title="Generated by AI"]')).toHaveLength(1);
    expect(wrapper.find('[title="Evaluation is obsolete after a scenario edit"]')).toHaveLength(1);
    expect(container.textContent).not.toMatch(/iteration|total|fix round|modified/i);
    wrapper.unmount();
  });

  test('renders Manual Ready status without inventing AI identity or missing metrics', () => {
    const { container, wrapper } = renderSummary(
      <NativeTestCaseSummary
        showIdentity
        summary={{ isAi: false, status: 'READY', isObsolete: false }}
      />,
    );

    expect(container.textContent).toBe('Ready');
    expect(wrapper.find('[title="Generated by AI"]')).toHaveLength(0);
    expect(container.textContent).not.toContain('★');
    expect(container.textContent).not.toContain('cost');
    wrapper.unmount();
  });

  test('renders only supplied metrics when identity is omitted', () => {
    const { container, wrapper } = renderSummary(
      <NativeTestCaseSummary
        summary={{ isAi: true, status: 'READY', score: 93, isObsolete: false, costUsd: 0.22 }}
      />,
    );

    expect(container.textContent).toBe('★ 93Current version cost: $0.22');
    expect(wrapper.find('[title="Evaluation is obsolete after a scenario edit"]')).toHaveLength(0);
    wrapper.unmount();
  });

  test('omits metrics in an identity-only header even when the backend supplies them', () => {
    const { container, wrapper } = renderSummary(
      <NativeTestCaseSummary
        showIdentity
        showMetrics={false}
        summary={{ isAi: true, status: 'DRAFT', score: 72, isObsolete: false, costUsd: 0.235 }}
      />,
    );

    expect(container.textContent).toBe('AIDraft');
    wrapper.unmount();
  });
});
